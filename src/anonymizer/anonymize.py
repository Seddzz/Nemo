"""Anonymizer: replace detected entities with stable placeholders or fakes."""
from anonymizer.detect import Entity, validate_entity_offsets
from anonymizer.fakes import FakeGenerator


def replacement_table(
    entities: list[Entity],
    strategy: str = "placeholder",
    faker: FakeGenerator | None = None,
) -> dict[tuple[str, str], str]:
    """Compute the ``(label, original) -> replacement`` table shared by the
    text pipeline and the PDF renderer so both produce identical tokens."""
    if strategy not in ("placeholder", "fake"):
        raise ValueError(f"unknown strategy: {strategy!r}")

    replacement_by_key: dict[tuple[str, str], str] = {}

    if strategy == "placeholder":
        counters: dict[str, int] = {}
        for entity in sorted(entities, key=lambda e: e.start):
            key = (entity.label, entity.text)
            if key in replacement_by_key:
                continue
            counters[entity.label] = counters.get(entity.label, 0) + 1
            replacement = f"[{entity.label}_{counters[entity.label]}]"
            replacement_by_key[key] = replacement
    else:
        generator = faker or FakeGenerator()
        used: set[str] = set()
        for entity in sorted(entities, key=lambda e: e.start):
            key = (entity.label, entity.text)
            if key in replacement_by_key:
                continue
            fake = generator.generate(entity.label)
            while fake in used:
                fake = generator.generate(entity.label)
            used.add(fake)
            replacement_by_key[key] = fake

    return replacement_by_key


def apply_replacements(
    text: str,
    entities: list[Entity],
    replacement_by_key: dict[tuple[str, str], str],
) -> str:
    """Splice every replacement into ``text`` right-to-left so earlier offsets stay valid."""
    redacted = text
    for entity in sorted(entities, key=lambda e: e.start, reverse=True):
        replacement = replacement_by_key[(entity.label, entity.text)]
        redacted = redacted[: entity.start] + replacement + redacted[entity.end :]
    return redacted


def anonymize_text(
    text: str,
    entities: list[Entity],
    strategy: str = "placeholder",
    faker: FakeGenerator | None = None,
    replacements: dict[tuple[str, str], str] | None = None,
) -> str:
    """Replace each entity span and return the redacted text.

    Redaction is one-way by design: there is no mapping kept, returned or
    stored anywhere. The same ``(label, value)`` pair always receives the same
    replacement, so repeated values stay consistent within a document.

    Strategy:
        ``"placeholder"`` (default) uses numbered tokens like ``[PERSON_1]``.
        ``"fake"`` uses realistic surrogates generated by :class:`FakeGenerator`.

    ``entities`` must be non-overlapping (the DetectionEngine guarantees this).
    """
    validate_entity_offsets(text, entities)
    table = (
        replacements
        if replacements is not None
        else replacement_table(entities, strategy=strategy, faker=faker)
    )
    return apply_replacements(text, entities, table)
